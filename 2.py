'''
Задача 1
При регистрации в компьютерной системе каждому объекту присваивается идентификатор, содержащий десятичные цифры, 
26 латинских букв в верхнем регистре и символы из 2013-символьного специального алфавита. 
В базе данных для хранения каждого идентификатора отведено одинаковое и минимально возможное число байт. 
При этом используется посимвольное кодирование идентификаторов, все символы кодируются одинаковым 
и минимально возможным числом бит. Известно, что для хранения 2050 идентификаторов отведено более 709 Кбайт памяти. 
Определите минимально возможную длину идентификатора. В ответе запишите только целое число
'''
from math import ceil, log2

N = 10 + 26 + 2013
I_2050 = 709 * 2 ** 10
ids = 2050

i = ceil(log2(N))
I = ceil(I_2050 / ids)
L = ceil(I * 8 / i)

print(L)

'''
Задача 2 
Автоматическая фотоловушка в заповеднике, оснащённая датчиком движения, делает цветные фотографии проходящих мимо леопардов. 
Размер каждой фотографии 1024 х 64 пикселя, при этом используется палитра из 4096 цветов. Снимки сохраняются в памяти камеры, 
группируются по несколько штук, а затем передаются в центр охраны природы со скоростью передачи данных 655 360 бит/с. 
Каково максимально возможное количество снимков в одном пакете, если на передачу одного пакета отводится не более 70 секунд.
В ответе запишите целое число
'''
from math import log2

res = 1024 * 64
bitrate = 655_360
colors = 4096
time = 70

pixel_size = log2(colors)
img_size = res * pixel_size
package_size = bitrate * time
img_in_package = package_size // img_size

print(img_in_package)

